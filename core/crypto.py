"""
Symmetric encryption for secrets stored at rest (e.g. Gmail OAuth refresh tokens).

Values are stored as "enc:v1:<fernet token>". Rows written before encryption was
enabled are plain strings and are still readable, so the change is backward compatible.
"""

import logging
from functools import lru_cache
from typing import Optional

from config.settings import settings

logger = logging.getLogger(__name__)

_PREFIX = "enc:v1:"


def _fernet_key(raw: str) -> bytes:
    """
    Accepts either a real Fernet key (urlsafe base64 of 32 bytes) or any other high-entropy
    secret, e.g. one generated by a hosting platform. Non-Fernet secrets are stretched into a
    Fernet key with SHA-256, so the same secret always yields the same key.
    """
    import base64
    import binascii
    import hashlib

    try:
        if len(base64.urlsafe_b64decode(raw.encode())) == 32:
            return raw.encode()
    except (binascii.Error, ValueError):
        pass
    return base64.urlsafe_b64encode(hashlib.sha256(raw.encode()).digest())


@lru_cache(maxsize=1)
def _fernet():
    raw = (settings.TOKEN_ENCRYPTION_KEY or "").strip()
    if not raw:
        return None
    from cryptography.fernet import Fernet
    return Fernet(_fernet_key(raw))


def encrypt_secret(value: Optional[str]) -> Optional[str]:
    if value is None:
        return None
    f = _fernet()
    if f is None:
        return value
    return _PREFIX + f.encrypt(value.encode()).decode()


def decrypt_secret(value: Optional[str]) -> Optional[str]:
    if value is None or not value.startswith(_PREFIX):
        return value
    f = _fernet()
    if f is None:
        raise RuntimeError("Encrypted secret found but TOKEN_ENCRYPTION_KEY is not configured.")
    return f.decrypt(value[len(_PREFIX):].encode()).decode()
